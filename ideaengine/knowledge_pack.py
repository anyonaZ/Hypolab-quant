def dead_ends(journal=None, min_tries: int = 5) -> str:
    lines = [_header("07_dead_ends.md", "Dead ends: families that produced no signal"),
             f"A family is listed when it has at least {min_tries} live tries and none reached WEAK or better. "
             "New cards in these families need a genuinely different mechanism or data, not a variation.\n"]
    rows = []
    if journal is not None:
        import sqlite3  # noqa: F401  (journal is a HYPOLAB Journal)
        q = """SELECT i.family, e.region, COUNT(*) AS tries,
               SUM(CASE WHEN e.verdict IN ('PASS','NEAR','WEAK') THEN 1 ELSE 0 END) AS signal,
               MAX(e.sharpe) AS best FROM experiments e JOIN ideas i ON e.idea_id = i.id
               WHERE e.backend != 'sandbox' AND e.purpose IN ('explore','boost') GROUP BY i.family, e.region"""
        for fam, reg, tries, signal, best in journal.db.execute(q).fetchall():
            if tries >= min_tries and not signal:
                rows.append(f"| {fam} | {reg} | {tries} | {best if best is None else round(best, 2)} |")
    if rows:
        lines += ["| Family | Region | Tries | Best Sharpe |", "|---|---|---|---|"] + rows
    else:
        lines.append("_None yet. This list fills in as the live journal grows._")
    return "\n".join(lines) + "\n"


def my_operator_usage(journal=None) -> str:
    lines = [_header("08_my_operator_usage.md", "Operators Zacc has and has not used this quarter")]
    try:
        from hypolab import account
        if journal is None or account.account_alphas(journal).empty:
            raise LookupError
        summary, by_cat, used, unused = account.operator_audit(journal)
    except Exception:  # noqa: BLE001
        lines.append("_Not available yet: download your submitted alphas on the cockpit's Account tab, then "
                     "regenerate this pack._")
        return "\n".join(lines) + "\n"
    lines += [f"Quarter {summary['quarter']}: {summary['regular counted']} regular alphas submitted, "
              f"{summary['distinct operators used']} of {summary['operators available']} operators used "
              f"(list from {summary['operator list from']}; {summary['left out of the count']} not counted).\n",
              "Rule for writers: choose operators for the mechanism. When two constructions test the idea equally "
              "well, prefer the one with an operator not used yet this quarter. Never add an operator only for "
              "coverage.\n", "| Category | Used / available | Not used yet |", "|---|---|---|"]
    for r in by_cat.itertuples(index=False):
        names = unused[unused["category"] == r.category]["operator"].tolist()
        lines.append(f"| {r.category} | {r.used}/{r.available} | {', '.join(names) or 'all used'} |")
    return "\n".join(lines) + "\n"


def brain_rules() -> str:
    """docs/BRAIN_RULES.md: what BRAIN's own pages say, with sources, conflicts and dataset notes."""
    path = config.PROJECT_DIR / "docs" / "BRAIN_RULES.md"
    body = path.read_text() if path.exists() else "_docs/BRAIN_RULES.md is missing from this install._\n"
    return _header("09_brain_rules.md", "BRAIN's rules, checked against HYPOLAB") + body


def build(out_dir: Path, journal=None, store=None) -> List[Path]:
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    files = {
        "01_card_format.md": card_format(),
        "02_concepts.md": concepts(),
        "03_operators.md": operators(),
        "04_existing_cards.md": existing_cards(journal),
        "05_pyramids_guide.md": pyramids_guide(),
        "06_goals_and_rules.md": goals_and_rules(store),
        "07_dead_ends.md": dead_ends(journal),
        "08_my_operator_usage.md": my_operator_usage(journal),
        "09_brain_rules.md": brain_rules(),
    }
    written = []
    for name, text in files.items():
        p = out / name
        p.write_text(text)
        written.append(p)
    index = ["# Knowledge pack - which file goes to which project", "",
             "| File | Upload to |", "|---|---|"] + [f"| {n} | {', '.join(u)} |" for n, u in USED_BY.items()]
    (out / "INDEX.md").write_text("\n".join(index) + "\n")
    return written + [out / "INDEX.md"]


def main(argv: Optional[List[str]] = None) -> int:
    argv = list(sys.argv[1:] if argv is None else argv)
    out = Path(argv[0]) if argv else Path("claude_projects") / "knowledge"
    journal = store = None
    try:
        from hypolab.journal import Journal
        from ideaengine.store import IdeaStore
        journal, store = Journal.open_readonly(), IdeaStore()
    except Exception as e:  # noqa: BLE001 - a pack without live data is still useful
        print(f"(no journal/goals read: {e})")
    for p in build(out, journal, store):
        print("wrote", p)
    return 0


if __name__ == "__main__":
    sys.exit(main())
