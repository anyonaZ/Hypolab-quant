def _header(name: str, title: str) -> str:
    return (f"# {title}\n\n_Generated by HYPOLAB on {dt.date.today().isoformat()} - upload to: "
            f"{', '.join(USED_BY[name])}. Do not edit by hand; regenerate instead._\n\n")


def _hint(pattern: str) -> str:
    """A readable hint from a concept's first matching pattern."""
    s = pattern.replace("\\b", "").replace(".?", " ").replace("\\s", " ")
    s = re.sub(r"\.\{\d+,\d+\}", " ... ", s)
    s = re.sub(r"\(([^()|]*)\|[^()]*\)", r"\1", s)        # (a|b) -> a
    s = re.sub(r"[()?^$\\]", "", s)
    return " ".join(s.split())


def card_format() -> str:
    raw = (config.LIBRARY_DIR / "hypotheses.yaml").read_text()
    blocks = re.split(r"(?m)^(?=- id: )", raw)
    examples = [b.rstrip() for b in blocks if any(b.startswith(f"- id: {i}\n") for i in EXAMPLE_CARDS)]
    windows = ", ".join(f"{k} ({v})" for k, v in config.ECONOMIC_WINDOWS.items())
    return _header("01_card_format.md", "HYPOLAB hypothesis card format") + f"""A card is an economic IDEA first and an
expression second. HYPOLAB loads cards written in exactly this YAML format (a list with one item per card).

## Fields
| Field | Required | Meaning |
|---|---|---|
| id | yes | Upper-case, unique. Cards from the idea team start with `IE_` (e.g. `IE_OPERATING_LEVERAGE`) |
| title | yes | One line, the idea in plain words |
| category | yes | `auto` (from the data used) or one of: {", ".join(CATEGORY_NAMES)} |
| family | yes | snake_case group of closely related ideas; alphas from one family correlate |
| horizon | yes | `fast` (days), `medium` (weeks to a quarter), `slow` (quarters to a year) |
| strength | yes | 3 = replicated in many markets, 2 = solid in papers, 1 = speculative |
| sign | yes | e.g. `"+1"` or `"+1 on minus past-week return"`: higher signal -> higher future return? |
| story | yes | The mechanism: who makes the mistake, and why prices adjust slowly |
| why_persists | yes | Why it is not arbitraged away: who is on the other side, what limits them |
| references | yes | Papers or sources; at least one |
| roles | yes | The data the idea needs, as CONCEPT names (see 02_concepts.md), never field ids. `{{}}` if only standard price/volume fields are used |
| ladder | yes | 1-3 rungs, simplest first. Each: `name`, `expr`, `teaches` |
| settings | yes | `{{neutralization: SUBINDUSTRY, decay: 0, truncation: 0.08}}` style |
| expected_turnover | yes | `[low, high]` as fractions, e.g. `[0.02, 0.15]` |
| watch_out | no | Known traps, a list of short lines |

## Rules for ladder expressions
- Use only operators from 03_operators.md, with named-only arguments named (e.g. `winsorize(x, std=4)`).
- Refer to data only as `{{role}}` placeholders (filled with real fields per region by HYPOLAB) or the standard
  fields that exist everywhere: close, open, high, low, vwap, volume, returns, adv20, cap, sharesout.
- `{{dir:role}}` becomes 1 or -1 from the field's description (use it when a vendor's direction is unclear).
- Quarterly data (fundamentals, estimates) needs `ts_backfill(x, 63)` or longer before time-series operators.
- Windows must mean something: {windows}. A window like 37 or 113 is flagged.
- Compare with peers: `group_rank(..., subindustry)` or neutralization; bound the output (rank / group_rank / zscore).
- Rung 1 is the plainest test of the mechanism; later rungs each change ONE thing for an economic reason.

## Two real cards to copy the style from
```yaml
{chr(10).join(examples)}
```
"""


def concepts() -> str:
    lines = [_header("02_concepts.md", "Economic concepts HYPOLAB can bind to real fields"),
             "A card's `roles` must use these names. HYPOLAB finds the best-covered, least-crowded field for each "
             "concept in each region. If an idea needs data that is not on this list, say so instead of inventing "
             "a concept.\n",
             "| Concept | Usual nature | What it matches |", "|---|---|---|"]
    for name, c in CONCEPTS.items():
        nat = ", ".join(c.natures) if c.natures else "-"
        what = c.note or _hint(c.include[0]) if c.include else c.note
        if c.canonical and c.canonical[0] in STANDARD_PV:
            what += f" (standard field `{c.canonical[0]}`: may also be written directly)"
        lines.append(f"| `{name}` | {nat} | {what} |")
    lines += ["", "## Field natures", "| Nature | Meaning |", "|---|---|"]
    lines += [f"| {k} | {v} |" for k, v in NATURES.items()]
    return "\n".join(lines) + "\n"


def operators() -> str:
    t = GOLD.table()
    lines = [_header("03_operators.md", "Operators available at Gold (the only ones allowed)"),
             "Anything not on this list is blocked by HYPOLAB's linter before it can cost a simulation. "
             "Arguments listed under *named-only* must be written as `name=value`.\n",
             "| Operator | Category | Signature | Named-only | Output | Use it for |", "|---|---|---|---|---|---|"]
    for r in t.itertuples(index=False):
        sig = str(r.signature).replace("|", "/")
        lines.append(f"| `{r.operator}` | {r.category} | `{sig}` | {r[4] or ''} | {r.output} | {r[6]} |")
    return "\n".join(lines) + "\n"


def existing_cards(journal=None) -> str:
    lib = load_library()
    status: Dict[str, str] = {}
    if journal is not None:
        ex = journal.experiments()
        if not ex.empty:
            ex = ex[ex["backend"] != "sandbox"]
            for hid, g in ex.groupby(ex["idea_id"].str.split("@").str[0]):
                v = g["verdict"].replace("", "-").value_counts()
                status[hid] = f"{len(g)} tries; " + ", ".join(f"{k} {n}" for k, n in v.items())
        sub = journal.submissions()
        for r in sub.itertuples(index=False):
            hid = str(r.idea_id).split("@")[0]
            status[hid] = status.get(hid, "") + " ; SUBMITTED"
    lines = [_header("04_existing_cards.md", "Idea cards HYPOLAB already has"),
             f"{len(lib)} cards. A new card that restates one of these (same mechanism, same data) is a duplicate; "
             "a new card in the same family will correlate with it.\n",
             "| id | source | category | family | title | live results |", "|---|---|---|---|---|---|"]
    for h in lib:
        lines.append(f"| {h.id} | {h.source} | {h.category} | {h.family} | {h.title} | {status.get(h.id, '-')} |")
    return "\n".join(lines) + "\n"


